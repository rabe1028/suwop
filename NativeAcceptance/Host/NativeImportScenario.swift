import Foundation
import SuwopShell

/// Exercises only the existing generated fixture assets and copies created by
/// this scenario. It never deletes an asset or calls a network provider.
@MainActor enum NativeImportScenario {
    private struct Evidence: Codable {
        var created: [AssetKey] = []
        var successful: [String] = []
        var lost: String?
    }

    private static var evidenceURL: URL {
        FixtureLibrary.root.appendingPathComponent("external-import-acceptance.json")
    }

    static func run(_ phase: String, manifest: FixtureManifest) async throws {
        var evidence: Evidence = if phase == "import-create" {
            Evidence()
        } else {
            try Wire.decoder().decode(Evidence.self, from: Data(contentsOf: evidenceURL))
        }
        let driver = try ImportAcceptanceDriver(allowed: manifest.keys + evidence.created)
        _ = try await driver.event("initialize", ["scope": .string(FixtureLibrary.scope)])
        _ = try await driver.event(
            "refresh",
            ["permission": .bool(false), "now": .number(Date().timeIntervalSince1970)]
        )
        switch phase {
        case "import-create": try await create(driver, manifest: manifest, evidence: &evidence)
        case "import-restart": try await restart(driver, manifest: manifest, evidence: &evidence)
        case "import-lost": try await lost(driver, manifest: manifest, evidence: &evidence)
        case "import-lost-restart": try await lostRestart(driver, manifest: manifest, evidence: &evidence)
        default: throw SuwopError("Unknown import fixture phase.")
        }
        try Wire.encoder().encode(evidence).write(to: evidenceURL, options: .atomic)
        try await verifyOriginals(manifest)
    }

    private static func create(
        _ driver: ImportAcceptanceDriver,
        manifest: FixtureManifest,
        evidence: inout Evidence
    ) async throws {
        let source = try await exportedFixture(manifest.keys[0])
        let operation = UUID().uuidString
        let urls = source.files.map { URL(fileURLWithPath: $0.path) }
        var items = try await driver.shell.importStaging.stage(urls, operation: operation)
        guard items.count == 1 else { throw SuwopError("Generated import is not one item.") }
        items[0] = NativeImportItem(id: items[0].id, resources: items[0].resources, metadata: NativeImportMetadata(
            capturedAt: "2023-11-14T22:13:20.125Z",
            latitude: 35.681,
            longitude: 139.767,
            favorite: true
        ))
        let view = try await driver.event("importStaged", [
            "id": .string(operation), "destination": .string("apple"),
            "items": .from(items), "now": .number(Date().timeIntervalSince1970),
        ])
        try recordVerified(view, operation: operation, originals: manifest.keys, evidence: &evidence)
        for key in view.externalImports.filter({ $0.stagingOperation == operation }).flatMap(\.destinationKeys) {
            let created = try await exportedFixture(key)
            guard let capture = created.assets.first?.capturedAt,
                  abs(capture.timeIntervalSince1970 - 1_700_000_000.125) < 0.001
            else {
                throw SuwopError("Fractional import capture date was not preserved by PhotoKit.")
            }
        }
        let duplicateID = UUID().uuidString
        let duplicate = try await driver.event("duplicate", [
            "id": .string(duplicateID), "destination": .string("apple"),
            "keys": .from([manifest.keys[1]]), "current": .bool(false),
            "now": .number(Date().timeIntervalSince1970),
        ])
        try recordVerified(duplicate, operation: duplicateID, originals: manifest.keys, evidence: &evidence)
        // Picker cancellation discards only staged generated bytes and
        // dispatches no Rust import command or native asset creation.
        let cancelled = UUID().uuidString
        _ = try await driver.shell.importStaging.stage(urls, operation: cancelled)
        let writes = driver.created.count
        try await driver.shell.importStaging.release(operation: cancelled)
        guard driver.created.count == writes else { throw SuwopError("Cancel created a photo.") }
    }

    private static func restart(
        _ driver: ImportAcceptanceDriver,
        manifest: FixtureManifest,
        evidence: inout Evidence
    ) async throws {
        let view = try await driver.runtime.view()
        for operation in evidence.successful {
            let records = view.externalImports.filter { $0.stagingOperation == operation }
            guard records.count == 1, records[0].phase == .verified,
                  records[0].destinationKeys.allSatisfy(evidence.created.contains)
            else {
                throw SuwopError("Verified import did not survive a process restart.")
            }
        }
        guard driver.created.isEmpty else { throw SuwopError("Restart resubmitted an import.") }
    }

    private static func lost(
        _ driver: ImportAcceptanceDriver,
        manifest: FixtureManifest,
        evidence: inout Evidence
    ) async throws {
        let operation = UUID().uuidString
        driver.loseCreationResponse = true
        let view = try await driver.event(
            "duplicate",
            [
                "id": .string(operation), "destination": .string("apple"),
                "keys": .from([manifest.keys[2]]), "current": .bool(false),
                "now": .number(Date().timeIntervalSince1970),
            ],
            allowError: true
        )
        guard view.error != nil, driver.created.count == 1,
              view.externalImports
              .contains(where: { $0.stagingOperation == operation && $0.phase == .uncertain })
        else {
            throw SuwopError("Lost PhotoKit create response did not preserve uncertainty.")
        }
        evidence.lost = operation
        evidence.created += driver.created
    }

    private static func lostRestart(
        _ driver: ImportAcceptanceDriver,
        manifest: FixtureManifest,
        evidence: inout Evidence
    ) async throws {
        let view = try await driver.runtime.view()
        guard let operation = evidence.lost,
              let record = view.externalImports.first(where: { $0.stagingOperation == operation }),
              record.phase == .uncertain, record.created == nil, driver.created.isEmpty
        else {
            throw SuwopError("Unknown import was retried or reclassified after restart.")
        }
        let inspected = try await driver.event("inspectImport", ["id": .string(record.id)], allowError: true)
        guard inspected.error != nil, driver.created.isEmpty else {
            throw SuwopError("Unknown ID must not be guessed or re-created.")
        }
    }

    private static func verifyOriginals(_ manifest: FixtureManifest) async throws {
        // Every original remains byte-identical and keeps its date/GPS/favorite.
        for (index, key) in manifest.keys.enumerated() {
            let current = try await exportedFixture(key)
            let expected = manifest.originals[index]
            let actualSignatures = current.files.map { "\($0.signature.sha256)|\($0.signature.bytes)" }
            let expectedSignatures = expected.files.map { "\($0.signature.sha256)|\($0.signature.bytes)" }
            guard actualSignatures == expectedSignatures,
                  current.assets[0].capturedAt == expected.assets[0].capturedAt,
                  current.assets[0].latitude == expected.assets[0].latitude,
                  current.assets[0].longitude == expected.assets[0].longitude,
                  current.assets[0].isFavorite == expected.assets[0].isFavorite
            else {
                throw SuwopError("Import changed a generated original.")
            }
        }
    }

    private static func recordVerified(
        _ view: ViewModel, operation: String, originals: [AssetKey], evidence: inout Evidence
    ) throws {
        let records = view.externalImports.filter { $0.stagingOperation == operation }
        guard records.count == 1, records[0].phase == .verified, records[0].created == true,
              !records[0].destinationKeys.isEmpty,
              records[0].destinationKeys.allSatisfy({ !originals.contains($0) && !evidence.created.contains($0) })
        else {
            throw SuwopError("Creation did not establish a new verified asset ID.")
        }
        evidence.created += records[0].destinationKeys
        evidence.successful.append(operation)
    }

    private static func exportedFixture(_ key: AssetKey) async throws -> TransferBundle {
        let directory = FixtureLibrary.root.appendingPathComponent("import-source-\(UUID().uuidString)")
        return try await ApplePhotosStore(scope: FixtureLibrary.scope).export([key], to: directory)
    }
}
